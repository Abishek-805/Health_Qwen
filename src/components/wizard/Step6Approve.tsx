import React, { useState } from 'react';
import {
  CheckCircle2,
  Download,
  ShieldCheck,
  XCircle,
  Award,
  UserCheck,
  FileCheck,
  AlertCircle,
} from 'lucide-react';
import {
  DischargeDocument,
} from '../../types/discharge';
import { StatusBadge } from '../common/StatusBadge';

interface Props {
  document: DischargeDocument;
  onApprovalSuccess: (updatedDoc: DischargeDocument) => void;
  clinicianName: string;
}

type DownloadState = 'idle' | 'generating' | 'success' | 'error';

export const Step6Approve: React.FC<Props> = ({
  document: doc,
  onApprovalSuccess,
  clinicianName,
}) => {
  const [role, setRole] = useState<string>('Attending Physician');
  const [signatureNote, setSignatureNote] = useState<string>(
    'Reviewed discharge summary, verified medication dosages, and confirmed patient understanding.'
  );
  const [isApproving, setIsApproving] = useState<boolean>(false);
  const [isApproved, setIsApproved] = useState<boolean>(doc.approvalStatus === 'APPROVED');

  const [downloadState, setDownloadState] = useState<DownloadState>('idle');
  const [downloadedFilename, setDownloadedFilename] = useState<string>('');
  const [downloadError, setDownloadError] = useState<string>('');

  const audit = doc.auditResult;
  const isCritical = audit?.overallStatus === 'CRITICAL_ISSUE';

  // ── Approval ─────────────────────────────────────────────────
  const handleApprove = async () => {
    if (isCritical) {
      alert('Approval is strictly blocked due to CRITICAL_ISSUE in hybrid safety audit.');
      return;
    }

    setIsApproving(true);
    try {
      const res = await fetch('/api/approve-instructions', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          documentId: doc.id,
          reviewerName: clinicianName,
          reviewerRole: role,
          signatureNote,
        }),
      });

      if (!res.ok) {
        const err = await res.json();
        throw new Error(err.message || err.error || 'Approval failed.');
      }

      // Server returns { success, document, message }
      const body = await res.json();
      const updatedDoc: DischargeDocument = body.document ?? body;

      setIsApproved(true);
      onApprovalSuccess(updatedDoc);
    } catch (err: any) {
      console.error('[Step6] Approval error:', err);
      alert(err.message || 'Failed to approve discharge instructions.');
    } finally {
      setIsApproving(false);
    }
  };

  // ── PDF Download — Official Production HTTP Endpoint ─────────
  // EXACTLY ONE production path:
  //   1) POST /api/precheck-approved-pdf (JSON) — server-side validation gate.
  //      If the server rejects the document (403 CRITICAL_AUDIT_BLOCK, 400 …)
  //      or is unreachable, the error is displayed. NO local fallback.
  //   2) Native HTML form POST → /api/generate-approved-pdf.
  //      The server replies with Content-Type: application/pdf and
  //      Content-Disposition: attachment; filename="Discharge_Instructions_…pdf".
  //      Chrome performs a native HTTP download using that filename.
  // No Blob, no object URL, no data URI, no anchor click, no jsPDF on the client.
  const handleDownloadPdf = async () => {
    console.log('[Step6] DOWNLOAD PDF clicked — prechecking then submitting native form POST to /api/generate-approved-pdf');
    setDownloadState('generating');
    setDownloadError('');

    if (isCritical) {
      setDownloadError('APPROVAL STRICTLY BLOCKED — Cannot download PDF with unresolved critical safety issues.');
      setDownloadState('error');
      return;
    }

    // 1) Server-side precheck — show real server errors instead of a blind form POST
    try {
      const pre = await fetch('/api/precheck-approved-pdf', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(doc),
      });

      if (!pre.ok) {
        const err = await pre.json().catch(() => null);
        setDownloadError(err?.message || err?.code || `Server rejected the PDF request (HTTP ${pre.status}).`);
        setDownloadState('error');
        return;
      }
    } catch (err: any) {
      console.error('[Step6] PDF precheck failed:', err);
      setDownloadError('PDF server is unreachable. The official PDF must be generated by the backend — no local fallback is permitted.');
      setDownloadState('error');
      return;
    }

    // 2) Native form POST — the browser receives the real HTTP PDF response
    try {
      const form = document.createElement('form');
      form.method = 'POST';
      form.action = '/api/generate-approved-pdf';
      form.target = '_self';
      form.style.display = 'none';

      const input = document.createElement('input');
      input.type = 'hidden';
      input.name = 'payload';
      input.value = JSON.stringify(doc);
      form.appendChild(input);

      document.body.appendChild(form);
      form.submit();

      setTimeout(() => {
        form.remove();
      }, 2000);

      const expectedFilename = `Discharge_Instructions_${doc.verifiedData?.patient?.name?.value || 'Patient'}_${doc.verifiedData?.patient?.patientId?.value || 'ID'}_v${doc.generatedReport?.version || 1}.pdf`;
      setDownloadedFilename(expectedFilename);
      setDownloadState('success');
    } catch (err: any) {
      console.error('[Step6] PDF download initiation error:', err);
      setDownloadError(err?.message || 'Failed to initiate PDF download.');
      setDownloadState('error');
    }
  };

  const isDownloading = downloadState === 'generating';

  return (
    <div className="mx-auto max-w-4xl p-6">
      <div className="rounded-[28px] bg-white p-8 shadow-xs border border-[#D9D1C5]/60">

        {/* Header */}
        <div className="flex items-center justify-between border-b border-[#F5F5F0] pb-5 mb-6">
          <div className="flex items-center gap-3.5">
            <div className="flex h-12 w-12 items-center justify-center rounded-full bg-[#5A5A40] text-white shadow-xs">
              <Award className="h-6 w-6" />
            </div>
            <div>
              <h3 className="font-serif italic text-xl text-[#3E4234] tracking-tight">
                Step 6 — Clinical Sign-Off &amp; PDF Handout Export
              </h3>
              <p className="text-xs text-[#8C8476] mt-0.5">
                Final clinician approval stamp for patient discharge handout (v{doc.generatedReport?.version}).
              </p>
            </div>
          </div>
          <StatusBadge status={doc.approvalStatus} size="lg" />
        </div>

        {/* Audit Status Guard */}
        {isCritical ? (
          <div className="mb-6 rounded-2xl bg-[#BC8F8F]/15 border border-[#BC8F8F]/40 p-5 text-[#8C4A4A]">
            <div className="flex items-start gap-3">
              <XCircle className="h-6 w-6 text-[#8C4A4A] shrink-0 mt-0.5" />
              <div>
                <h4 className="text-sm font-extrabold text-[#8C4A4A]">
                  APPROVAL STRICTLY BLOCKED — CRITICAL SAFETY ISSUES
                </h4>
                <p className="text-xs mt-1 leading-relaxed">
                  The hybrid safety audit flagged <strong>{audit?.criticalCount} critical discrepancy(ies)</strong> between
                  the verified patient data and generated handout. Return to Step 4 or Step 5 to resolve all critical
                  findings before sign-off.
                </p>
              </div>
            </div>
          </div>
        ) : (
          <div className="mb-6 rounded-2xl bg-[#5A5A40]/15 border border-[#5A5A40]/30 p-5 text-[#3E4234] flex items-start gap-3">
            <ShieldCheck className="h-6 w-6 text-[#5A5A40] shrink-0 mt-0.5" />
            <div>
              <h4 className="text-sm font-extrabold text-[#3E4234]">
                SAFETY CHECKS CLEAR — READY FOR CLINICIAN APPROVAL
              </h4>
              <p className="text-xs mt-0.5 leading-relaxed text-[#8C8476]">
                Report version v{doc.generatedReport?.version} has passed all safety checks. Click below to digitally
                attest and download the A4 PDF handout.
              </p>
            </div>
          </div>
        )}

        {/* Patient Summary */}
        <div className="mb-6 rounded-2xl border border-[#D9D1C5] bg-[#F5F5F0]/50 p-5 grid grid-cols-2 sm:grid-cols-4 gap-4 text-xs">
          <div>
            <span className="text-[#8C8476] font-bold block text-[10px] uppercase">Patient Name</span>
            <span className="font-extrabold text-[#3E4234] text-sm">
              {doc.verifiedData?.patient?.name?.value ?? '—'}
            </span>
          </div>
          <div>
            <span className="text-[#8C8476] font-bold block text-[10px] uppercase">Patient ID</span>
            <span className="font-bold font-mono text-[#5A5A40]">
              {doc.verifiedData?.patient?.patientId?.value ?? '—'}
            </span>
          </div>
          <div>
            <span className="text-[#8C8476] font-bold block text-[10px] uppercase">Language</span>
            <span className="font-bold text-[#3E4234] uppercase">
              {doc.generatedReport?.language ?? '—'}
            </span>
          </div>
          <div>
            <span className="text-[#8C8476] font-bold block text-[10px] uppercase">Document Version</span>
            <span className="font-bold text-[#5A5A40]">v{doc.generatedReport?.version ?? '—'}</span>
          </div>
        </div>

        {/* Clinician Attestation Form */}
        <div className="space-y-4 mb-8 border-t border-[#F5F5F0] pt-6">
          <h4 className="text-xs font-bold uppercase tracking-wider text-[#3E4234] flex items-center gap-2">
            <UserCheck className="h-4 w-4 text-[#5A5A40]" /> Clinician Digital Attestation
          </h4>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
            <div>
              <label className="text-xs font-bold text-[#3E4234] block mb-1">Clinician Name</label>
              <input
                type="text"
                value={clinicianName}
                disabled
                className="w-full rounded-2xl border border-[#D9D1C5] p-3 text-xs font-bold text-[#3E4234] bg-[#F5F5F0] cursor-not-allowed"
              />
            </div>
            <div>
              <label className="text-xs font-bold text-[#3E4234] block mb-1">Clinical Role / Title</label>
              <input
                type="text"
                value={role}
                onChange={(e) => setRole(e.target.value)}
                className="w-full rounded-2xl border border-[#D9D1C5] p-3 text-xs font-medium text-[#3E4234] focus:border-[#5A5A40] focus:bg-white focus:outline-none bg-[#F5F5F0]/50 transition-all"
                placeholder="Attending Physician / Chief Resident"
              />
            </div>
          </div>

          <div>
            <label className="text-xs font-bold text-[#3E4234] block mb-1">Approval Signature Note</label>
            <input
              type="text"
              value={signatureNote}
              onChange={(e) => setSignatureNote(e.target.value)}
              className="w-full rounded-2xl border border-[#D9D1C5] p-3 text-xs text-[#3E4234] focus:border-[#5A5A40] focus:bg-white focus:outline-none bg-[#F5F5F0]/50 transition-all"
            />
          </div>
        </div>

        {/* Download success/error feedback */}
        {downloadState === 'success' && downloadedFilename && (
          <div className="mb-4 rounded-2xl bg-emerald-50 border border-emerald-200 p-4 flex items-start gap-3">
            <CheckCircle2 className="h-5 w-5 text-emerald-600 shrink-0 mt-0.5" />
            <div>
              <p className="text-xs font-bold text-emerald-800">Official PDF download started.</p>
              <p className="text-xs text-emerald-700 mt-0.5 font-mono">{downloadedFilename}</p>
            </div>
          </div>
        )}
        {downloadState === 'error' && downloadError && (
          <div className="mb-4 rounded-2xl bg-red-50 border border-red-200 p-4 flex items-start gap-3">
            <AlertCircle className="h-5 w-5 text-red-600 shrink-0 mt-0.5" />
            <div>
              <p className="text-xs font-bold text-red-800">PDF GENERATION FAILED</p>
              <p className="text-xs text-red-700 mt-0.5">{downloadError}</p>
            </div>
          </div>
        )}

        {/* Action Buttons */}
        <div className="flex flex-col sm:flex-row items-center justify-between gap-4 border-t border-[#F5F5F0] pt-6">
          {!isApproved ? (
            <button
              type="button"
              id="step6-approve-btn"
              onClick={handleApprove}
              disabled={isCritical || isApproving}
              className="w-full sm:w-auto flex items-center justify-center gap-2 rounded-2xl bg-[#5A5A40] px-8 py-3.5 text-xs font-bold text-white shadow-xs hover:bg-[#4A4A34] active:scale-95 transition-all cursor-pointer disabled:opacity-40 disabled:cursor-not-allowed uppercase tracking-wider"
            >
              <CheckCircle2 className="h-4 w-4" />
              <span>{isApproving ? 'RECORDING APPROVAL...' : 'SIGN & APPROVE DISCHARGE HANDOUT'}</span>
            </button>
          ) : (
            <div className="flex items-center gap-2 rounded-2xl bg-[#5A5A40]/15 text-[#3E4234] border border-[#5A5A40]/30 px-5 py-2.5 text-xs font-bold">
              <FileCheck className="h-4 w-4 text-[#5A5A40]" />
              <span>OFFICIALLY APPROVED &amp; SIGNED</span>
            </div>
          )}

          <button
            type="button"
            id="step6-download-pdf-btn"
            disabled={isDownloading}
            onClick={handleDownloadPdf}
            className="w-full sm:w-auto flex items-center justify-center gap-2 rounded-2xl bg-[#5A5A40] px-8 py-3.5 text-xs font-bold text-white shadow-xs hover:bg-[#4A4A34] active:scale-95 transition-all cursor-pointer disabled:opacity-50 disabled:cursor-not-allowed uppercase tracking-wider"
          >
            <Download className={`h-4 w-4 ${isDownloading ? 'animate-bounce' : ''}`} />
            <span>
              {isDownloading
                ? 'GENERATING PDF...'
                : downloadState === 'success'
                ? 'DOWNLOAD STARTED'
                : 'DOWNLOAD PDF'}
            </span>
          </button>
        </div>
      </div>
    </div>
  );
};
